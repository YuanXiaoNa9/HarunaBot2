pub(super) async fn render(query: &str, items: &Vec<Box<dyn FnHandler + Send + Sync>>) -> String {
    if let Some(missing) = query.split('-').skip(1).find(|name| {
        !name.eq_ignore_ascii_case("all")
            && !ITEMS.iter().any(|(n, _)| n.eq_ignore_ascii_case(name))
    }) {
        return format!(
            "未找到子功能：{}\n\n查看子功能列表：/help PJSK数据上传",
            line(missing)
        );
    }
    let details = sub_help(query, items)
        .await
        .replace("机厅管理-添加-删除", "PJSK数据上传-绑定账号-更新数据");
    if query.contains('-') {
        return details;
    }
    format!(
        "将游戏数据上传到 Sakura，供相关 Bot 生成成绩图。\n\n首次使用\n1. 在开放群发送：/pjsk 申请绑定\n2. 私聊绑定账号，并同意条款\n3. 绑定成功后发送：/pjsk 更新数据\n\n子功能\n{details}"
    )
}
